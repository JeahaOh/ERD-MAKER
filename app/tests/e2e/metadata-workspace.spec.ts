import { expect, test } from '@playwright/test';
import { readFileSync } from 'node:fs';
import type { BinaryRegistry } from '../../src/formats/exerd/binary';
import { openNativeDocument } from '../../src/formats/exerd/native-document';
const registry = JSON.parse(readFileSync('app/src/formats/exerd/schema.generated.json', 'utf8')) as BinaryRegistry;

test('domain edits propagate inherited values, preserve exceptions and can reset an override', async ({ page }) => {
  await page.goto('/');
  await page.locator('.welcome').getByRole('button', { name: '새 모델', exact: true }).click();
  await page.getByLabel('새 모델 이름').fill('도메인 상속 검증');
  await page.getByRole('button', { name: '모델 만들기', exact: true }).click();
  await expect(page.locator('.entity-tree > button')).toHaveCount(1);
  await page.getByRole('button', { name: '도메인 추가', exact: true }).click();
  await page.getByLabel('도메인 추가 이름').fill('공통 코드');
  await page.getByRole('dialog', { name: '도메인 추가', exact: true }).getByRole('button', { name: '적용', exact: true }).click();
  await expect(page.locator('.statusbar')).toContainText('1 도메인');
  await page.locator('.entity-tree > button').click();
  await page.getByRole('button', { name: '컬럼', exact: true }).click();
  await page.getByLabel('컬럼 추가 이름').fill('code');
  await page.getByRole('dialog', { name: '컬럼 추가', exact: true }).getByRole('button', { name: '적용', exact: true }).click();
  await expect(page.locator('.column-list > button')).toHaveCount(2);
  await page.locator('.column-list > button').filter({ hasText: 'code' }).click();
  await page.getByLabel('컬럼 도메인').selectOption({ label: '공통 코드 · BIGINT' });
  await expect(page.getByLabel('컬럼 도메인')).not.toHaveValue('');
  await page.locator('.explorer-tabs').getByRole('button', { name: '도메인', exact: true }).click();
  await page.locator('.entity-tree > button').click();
  await page.getByLabel('도메인 자료형', { exact: true }).fill('VARCHAR(18)');
  await page.getByLabel('도메인 자료형', { exact: true }).press('Enter');
  await expect(page.locator('.entity-tree > button')).toContainText('VARCHAR(18)');
  await page.locator('.explorer-tabs').getByRole('button', { name: '테이블', exact: true }).click();
  await page.locator('.entity-tree > button').click();
  await page.locator('.column-list > button').filter({ hasText: 'code' }).click();
  await expect(page.getByLabel('자료형', { exact: true })).toHaveValue('VARCHAR(18)');
  await page.getByLabel('자료형', { exact: true }).fill('CHAR(5)'); await page.getByLabel('자료형', { exact: true }).press('Enter');
  await expect(page.locator('.column-list > button').filter({ hasText: 'code' })).toContainText('CHAR(5)');
  await page.locator('.explorer-tabs').getByRole('button', { name: '도메인', exact: true }).click(); await page.locator('.entity-tree > button').click();
  await page.getByLabel('도메인 자료형', { exact: true }).fill('VARCHAR(24)'); await page.getByLabel('도메인 자료형', { exact: true }).press('Enter');
  await expect(page.locator('.entity-tree > button')).toContainText('VARCHAR(24)');
  await page.locator('.explorer-tabs').getByRole('button', { name: '테이블', exact: true }).click(); await page.locator('.entity-tree > button').click();
  await page.locator('.column-list > button').filter({ hasText: 'code' }).click();
  await expect(page.getByLabel('자료형', { exact: true })).toHaveValue('CHAR(5)');
  await page.getByRole('button', { name: '도메인 기본값 적용', exact: true }).click();
  await expect(page.getByLabel('자료형', { exact: true })).toHaveValue('VARCHAR(24)');
});

test('SQL Server model creation preserves product identity and DB-specific properties in the saved file', async ({ page }) => {
  await page.goto('/'); await page.locator('.welcome').getByRole('button', { name: '새 모델', exact: true }).click();
  await page.getByLabel('새 모델 이름').fill('SQL Server 파일 검증');
  await page.getByLabel('새 모델 데이터베이스').selectOption('com.tomato.db.sqlserver_2005');
  await page.getByRole('button', { name: '모델 만들기', exact: true }).click();
  await expect(page.locator('.engine-badge')).toHaveText('SQL Server');
  await expect(page.locator('.entity-tree > button')).toHaveCount(1);
  const waiting = page.waitForEvent('download');
  await page.getByRole('button', { name: '파일 저장', exact: true }).click();
  const document = openNativeDocument(readFileSync((await (await waiting).path())!), registry);
  expect(document.graph.objects.find(o => o.class.name === 'Document')?.features.find(f => f.name === 'productId')?.value).toBe('com.tomato.db.sqlserver_2005');
  expect(document.graph.objects.some(o => o.class.packageUri === 'http://exerd.tomato.com/sqlserver/model')).toBe(true);
  expect(document.graph.objects.some(o => o.class.packageUri === 'http://exerd.tomato.com/postgresql/model')).toBe(false);
  await page.getByRole('button', { name: 'SQL', exact: true }).click();
  await expect(page.getByLabel('생성 SQL')).toContainText('CREATE TABLE [default_schema].[new_table]');
  await expect(page.getByRole('button', { name: 'SQL 파일 저장', exact: true })).toBeEnabled();
});

test('MySQL export uses its own syntax and blocks unverified cross-database conversion', async ({ page }) => {
  await page.goto('/'); await page.locator('.welcome').getByRole('button', { name: '새 모델', exact: true }).click();
  await page.getByLabel('새 모델 이름').fill('MySQL 내보내기 검증');
  await page.getByLabel('새 모델 데이터베이스').selectOption('com.tomato.db.mysql');
  await page.getByRole('button', { name: '모델 만들기', exact: true }).click();
  await expect(page.locator('.entity-tree > button')).toHaveCount(1);
  await page.getByRole('button', { name: 'SQL', exact: true }).click();
  await expect(page.getByLabel('생성 SQL')).toContainText('CREATE TABLE `default_schema`.`new_table`');
  await expect(page.getByRole('button', { name: 'SQL 파일 저장', exact: true })).toBeEnabled();
  const waiting = page.waitForEvent('download');
  await page.getByRole('button', { name: 'SQL 파일 저장', exact: true }).click();
  const sql = readFileSync((await (await waiting).path())!, 'utf8');
  expect(sql).toContain('PRIMARY KEY (`id` ASC)');
  expect(sql).not.toContain('SET standard_conforming_strings');
  await page.getByLabel('SQL 데이터베이스').selectOption('postgresql');
  await expect(page.getByLabel('생성 SQL')).toHaveValue('');
  await expect(page.getByRole('dialog', { name: 'SQL 내보내기' })).toContainText('DB 간 타입');
  await expect(page.getByRole('button', { name: 'SQL 파일 저장', exact: true })).toBeDisabled();
});
