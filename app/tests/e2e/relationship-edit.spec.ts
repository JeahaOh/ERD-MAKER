import { expect, test, type Page } from '@playwright/test';
import { mkdirSync, readFileSync } from 'node:fs';
import { createNativeDocument, appendNativeTable, rebuildNativeDocument, nativeGraph } from '../../src/formats/exerd/create';
import { mutateNativeDocument } from '../../src/formats/exerd/mutations';
import { openNativeDocument, saveNativeDocument } from '../../src/formats/exerd/native-document';
import { projectNativeDocument } from '../../src/formats/exerd/view';
import { generateNativeDdl } from '../../src/formats/sql/native-ddl';
import { compareNativeDocuments } from '../../src/formats/exerd/compare';
import type { BinaryRegistry } from '../../src/formats/exerd/binary';
const registry = JSON.parse(readFileSync('app/src/formats/exerd/schema.generated.json', 'utf8')) as BinaryRegistry;
async function downloadDocument(page: Page) {
  const waiting = page.waitForEvent('download');
  await page.getByRole('button', { name: '파일 저장', exact: true }).click();
  const downloaded = await waiting;
  return { downloaded, saved: openNativeDocument(readFileSync((await downloaded.path())!), registry) };
}

test('selected relationship edits composite mapping, parent key, identification and independent names without replacing the FK', async ({ page }) => {
  let document = appendNativeTable(createNativeDocument('관계 수정 브라우저 검증'), { name: 'child', x: 650, y: 100 });
  for (const table of projectNativeDocument(document).allTables) document = mutateNativeDocument(document, { type: 'addColumn', tableUuid: table.uuid, name: 'code', dataType: 'BIGINT' });
  let [parent, child] = projectNativeDocument(document).allTables;
  document = mutateNativeDocument(document, { type: 'setPrimaryKey', tableUuid: parent.uuid, columnUuids: parent.columns.map(c => c.uuid) });
  [parent, child] = projectNativeDocument(document).allTables;
  document = mutateNativeDocument(document, { type: 'addRelationship', name: 'fk_edit', parentTableUuid: parent.uuid, childTableUuid: child.uuid, parentColumnUuids: parent.columns.map(c => c.uuid), childColumnUuids: child.columns.map(c => c.uuid) });
  document = mutateNativeDocument(document, { type: 'addColumnGroup', kind: 'unique', tableUuid: parent.uuid, name: 'uk_code', columnUuids: [parent.columns[1].uuid] });
  const { field, set, uuid } = nativeGraph;
  const group = document.graph.objects.find(o => o.class.name === 'ForeignKeyColumnGroup')!;
  const constraint = document.graph.objects.find(o => o.class.name === 'ForeignKeyConstraint')!;
  const properties = document.graph.objects.find(o => o.id === (field(constraint, 'physicalProperties') as { ref: number }).ref)!;
  set(group, 'useIndexing', true); set(properties, 'onDeleteRule', 'CASCADE'); set(properties, 'deferrable', true);
  document = rebuildNativeDocument(document.graph);
  const original = projectNativeDocument(document).allRelationships[0], uniqueKey = projectNativeDocument(document).allTables[0].groups.find(g => g.kind === 'unique')!;
  await page.goto('/'); await page.getByLabel('eXERD 모델 파일', { exact: true }).setInputFiles({ name: '관계 수정.exerd', mimeType: 'application/octet-stream', buffer: Buffer.from(saveNativeDocument(document)) });
  await expect(page.locator('.react-flow__edge')).toHaveCount(1);
  await page.getByRole('button', { name: '전체 화면에 맞추기', exact: true }).click();
  const edge = page.getByRole('button', { name: '관계 fk_edit · public.child', exact: true });
  await edge.click();
  await expect(page.locator('.relationship-inspector')).toBeVisible();
  await edge.press('Escape'); await expect(page.locator('.relationship-inspector')).not.toBeVisible();
  const linePoint = await edge.locator('.react-flow__edge-interaction').evaluate(element => {
    const path = element as SVGPathElement;
    const point = path.getPointAtLength(path.getTotalLength() * 0.25).matrixTransform(path.getScreenCTM()!);
    return { x: point.x, y: point.y };
  });
  await page.mouse.click(linePoint.x, linePoint.y);
  await expect(page.locator('.relationship-inspector')).toBeVisible();
  await edge.press('Escape'); await expect(page.locator('.relationship-inspector')).not.toBeVisible();
  await edge.press('Enter'); await expect(page.locator('.relationship-inspector')).toBeVisible();
  await edge.press('Escape');
  await page.keyboard.press('Tab'); await expect(edge).not.toBeFocused();
  await page.keyboard.press('Shift+Tab'); await expect(edge).toBeFocused();
  await page.keyboard.press('Space'); await expect(page.locator('.relationship-inspector')).toBeVisible();
  await page.getByLabel('자식 카디널리티', { exact: true }).selectOption('ZERO_OR_ONE');
  await page.getByRole('button', { name: '관계 변경 적용', exact: true }).click();
  await expect(page.locator('.react-flow__edge-text')).toContainText('1 : 0..1');
  const cardinalityOnly = (await downloadDocument(page)).saved;
  expect(compareNativeDocuments(document, cardinalityOnly).changes.map(c => c.feature)).toEqual(['childCardinalityType']);
  expect(generateNativeDdl(cardinalityOnly).sql).toBe(generateNativeDdl(document).sql);
  await page.getByLabel('대응 컬럼: id', { exact: true }).selectOption(child.columns[1].uuid);
  await expect(page.getByRole('button', { name: '관계 변경 적용', exact: true })).toBeDisabled();
  await expect(page.locator('.relationship-inspector')).toContainText('서로 다른 자식 컬럼');
  await page.getByLabel('대응 컬럼: code', { exact: true }).selectOption(child.columns[0].uuid);
  await page.getByLabel('자식 카디널리티', { exact: true }).selectOption('ZERO_OR_ONE');
  await page.getByRole('button', { name: '관계 변경 적용', exact: true }).click();
  await expect(page.getByRole('button', { name: '관계 변경 적용', exact: true })).toBeDisabled();
  await expect(page.locator('.react-flow__edge-text')).toContainText('1 : 0..1');
  await page.getByRole('button', { name: '실행 취소', exact: true }).click();
  await expect(page.getByLabel('대응 컬럼: id', { exact: true })).toHaveValue(child.columns[0].uuid);
  await page.getByRole('button', { name: '다시 실행', exact: true }).click();
  await expect(page.getByLabel('대응 컬럼: id', { exact: true })).toHaveValue(child.columns[1].uuid);
  await page.getByLabel('관계 부모 키', { exact: true }).selectOption(uniqueKey.uuid);
  await page.getByLabel('대응 컬럼: code', { exact: true }).selectOption(child.columns[1].uuid);
  await page.getByLabel('관계 식별 여부', { exact: true }).check();
  await page.getByRole('button', { name: '관계 변경 적용', exact: true }).click();
  await expect(page.getByRole('button', { name: '관계 변경 적용', exact: true })).toBeDisabled();
  const identified = (await downloadDocument(page)).saved;
  expect(projectNativeDocument(identified).allRelationships[0].identifying).toBe(true);
  const childPkIds = projectNativeDocument(identified).allTables.find(t => t.uuid === child.uuid)!.groups.find(g => g.kind === 'primary')!.columnUuids;
  expect(childPkIds).toEqual(child.columns.map(c => c.uuid));
  const pkMembershipIds = identified.graph.objects.filter(o => o.class.name === 'PrimaryKeyMembership').map(o => uuid(o));
  await page.getByLabel('관계 식별 여부', { exact: true }).uncheck();
  await page.getByRole('button', { name: '관계 변경 적용', exact: true }).click();
  await expect(page.getByRole('button', { name: '관계 변경 적용', exact: true })).toBeDisabled();
  await page.getByLabel('관계 그룹 이름', { exact: true }).fill('fk_group_renamed'); await page.getByLabel('관계 그룹 이름', { exact: true }).press('Enter');
  await expect(page.getByLabel('외래키 제약 이름', { exact: true })).toHaveValue('fk_edit');
  await page.getByLabel('외래키 제약 이름', { exact: true }).fill('fk_constraint_renamed'); await page.getByLabel('외래키 제약 이름', { exact: true }).press('Enter');
  await expect(page.getByLabel('외래키 제약 이름', { exact: true })).toHaveValue('fk_constraint_renamed');
  const { downloaded, saved } = await downloadDocument(page), view = projectNativeDocument(saved);
  expect(view.allRelationships[0]).toMatchObject({ uuid: original.uuid, constraintUuid: original.constraintUuid, parentKeyUuid: uniqueKey.uuid, parentColumnUuids: [parent.columns[1].uuid], childColumnUuids: [child.columns[1].uuid], name: 'fk_group_renamed', constraintName: 'fk_constraint_renamed', identifying: false, childCardinality: 'ZERO_OR_ONE', onDelete: 'CASCADE' });
  expect(saved.byUuid.get(uuid(properties)!)!.features).toEqual(document.byUuid.get(uuid(properties)!)!.features);
  expect(field(saved.byUuid.get(original.uuid)!, 'useIndexing')).toBe(true);
  expect(saved.graph.objects.filter(o => o.class.name === 'PrimaryKeyMembership').map(o => uuid(o))).toEqual(pkMembershipIds);
  expect(view.allTables.find(t => t.uuid === child.uuid)!.columns.every(c => c.primaryKey)).toBe(true);
  expect(generateNativeDdl(saved).sql).toContain('CONSTRAINT "fk_constraint_renamed" FOREIGN KEY ("code") REFERENCES "public"."new_table" ("code")');
  mkdirSync('.analysis/compatibility', { recursive: true }); await downloaded.saveAs('.analysis/compatibility/browser-relationship-edited.exerd');
  await page.screenshot({ path: 'test-results/relationship-edit.png', fullPage: true });
});
