import { expect, test } from '@playwright/test';
import { readFileSync } from 'node:fs';
import type { BinaryRegistry } from '../../src/formats/exerd/binary';
import { openNativeDocument } from '../../src/formats/exerd/native-document';
import { projectNativeDocument } from '../../src/formats/exerd/view';
const registry = JSON.parse(readFileSync('app/src/formats/exerd/schema.generated.json', 'utf8')) as BinaryRegistry;

test('indexes, CHECK, notes, layout and PostgreSQL export share the native model', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await expect(page.locator('.app-header')).toHaveCSS('background-color', 'rgb(58, 74, 90)');
  await expect(page.locator('.flow-host')).toHaveCSS('background-color', 'rgb(249, 249, 249)');
  await expect(page.locator('.header-primary')).toHaveCSS('background-color', 'rgb(0, 161, 155)');
  await expect(page.locator('.header-primary')).toHaveCSS('color', 'rgb(38, 38, 38)');
  await page.locator('.welcome').getByRole('button', { name: '새 모델', exact: true }).click();
  await page.getByRole('button', { name: '모델 만들기', exact: true }).click();
  await expect(page.locator('.entity-tree > button')).toHaveCount(1);
  await page.locator('.entity-tree > button').click();
  await page.getByRole('button', { name: '컬럼', exact: true }).click();
  await page.getByLabel('컬럼 추가 이름').fill('code');
  await page.getByLabel('컬럼 추가 자료형').fill('VARCHAR(20)');
  await page.getByRole('button', { name: '적용', exact: true }).click();
  await expect(page.locator('.column-list > button')).toHaveCount(2);
  await page.getByRole('button', { name: '키 또는 인덱스 추가', exact: true }).click();
  await page.getByLabel('새 키 이름').fill('ix_code');
  await page.getByRole('dialog', { name: '키·인덱스 추가' }).getByRole('checkbox', { name: 'code', exact: true }).check();
  await page.getByLabel('code 정렬').selectOption('DESC');
  await page.getByRole('dialog', { name: '키·인덱스 추가' }).getByRole('button', { name: '추가', exact: true }).click();
  await expect(page.locator('.constraint-card').filter({ hasText: 'ix_code' })).toBeVisible();
  await page.getByRole('button', { name: 'CHECK 제약 추가', exact: true }).click();
  await page.getByLabel('새 CHECK 이름').fill('ck_positive');
  await page.getByLabel('새 CHECK 표현식').fill('id > 0');
  await page.getByRole('dialog', { name: 'CHECK 제약 추가', exact: true }).getByRole('button', { name: '추가', exact: true }).click();
  await expect(page.locator('.constraint-card').filter({ hasText: 'ck_positive' })).toBeVisible();
  await page.getByRole('button', { name: '메모', exact: true }).click();
  await page.getByLabel('새 메모 내용').fill('독립 모델 메모\n한글 é 😀');
  await page.getByRole('dialog', { name: '메모 추가', exact: true }).getByRole('button', { name: '추가', exact: true }).click();
  await expect(page.locator('.react-flow__node-note')).toHaveCount(1);
  await page.locator('.react-flow__node-note').click();
  await page.getByLabel('메모 내용', { exact: true }).fill('메모 편집\n둘째 줄');
  await page.getByLabel('메모 내용', { exact: true }).press('Tab');
  await expect(page.locator('.note-text')).toHaveText('메모 편집\n둘째 줄');
  await page.getByRole('button', { name: '자동 배치', exact: true }).click();
  await expect(page.getByRole('status').filter({ hasText: '자동 배치를 적용했습니다.' })).toBeVisible();
  await page.getByRole('button', { name: 'SQL', exact: true }).click();
  await expect(page.getByLabel('생성 SQL')).toContainText('CREATE TABLE');
  const sql = await page.getByLabel('생성 SQL').inputValue();
  expect(sql).toContain('"ix_code"'); expect(sql).toContain('DESC'); expect(sql).toContain('"ck_positive"'); expect(sql).toContain('"pk_new_table"');
  const sqlDownload = page.waitForEvent('download');
  await page.getByRole('button', { name: 'SQL 파일 저장', exact: true }).click();
  expect(readFileSync((await (await sqlDownload).path())!, 'utf8')).toBe(sql);
  await page.getByRole('dialog', { name: 'SQL 내보내기', exact: true }).getByRole('button', { name: '닫기', exact: true }).last().click();
  const nativeDownload = page.waitForEvent('download'); await page.getByRole('button', { name: '파일 저장', exact: true }).click();
  const view = projectNativeDocument(openNativeDocument(readFileSync((await (await nativeDownload).path())!), registry));
  expect(view.allTables[0].groups.find(g => g.name === 'ix_code')?.sortTypes).toEqual(['DESC']);
  expect(view.allTables[0].checks.map(c => c.expression)).toEqual(['id > 0']);
  expect(view.allNotes[0].text).toBe('메모 편집\n둘째 줄');
  await page.locator('summary').filter({ hasText: '내보내기' }).click();
  const vectorDownload = page.waitForEvent('download');
  await page.getByRole('button', { name: '다이어그램 SVG', exact: true }).click();
  const vector = readFileSync((await (await vectorDownload).path())!, 'utf8');
  expect(vector).toContain('<svg'); expect(vector).toContain('메모 편집'); expect(vector).toContain('code');
  const imageDownload = page.waitForEvent('download');
  await page.getByRole('button', { name: '다이어그램 PNG', exact: true }).click();
  const image = readFileSync((await (await imageDownload).path())!);
  expect([...image.subarray(0, 8)]).toEqual([137, 80, 78, 71, 13, 10, 26, 10]);
  expect(image.readUInt32BE(16)).toBeGreaterThan(300); expect(image.readUInt32BE(20)).toBeGreaterThan(100);
  const reportDownload = page.waitForEvent('download');
  await page.getByRole('button', { name: '정의서 HTML', exact: true }).click();
  const report = readFileSync((await (await reportDownload).path())!, 'utf8');
  expect(report).toContain('ck_positive'); expect(report).toContain('ix_code'); expect(report).not.toContain('<script');
  const csvDownload = page.waitForEvent('download');
  await page.getByRole('button', { name: '정의서 CSV', exact: true }).click();
  const csv = readFileSync((await (await csvDownload).path())!, 'utf8');
  expect(csv.charCodeAt(0)).toBe(0xfeff); expect(csv).toContain('code');
  await page.locator('summary').filter({ hasText: '내보내기' }).click();
  await page.screenshot({ path: 'test-results/advanced-model.png', fullPage: true });
  expect(errors).toEqual([]);
});
