import { expect, test } from '@playwright/test';
import { existsSync, readFileSync, mkdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import type { BinaryRegistry } from '../../src/formats/exerd/binary';
import { openNativeDocument } from '../../src/formats/exerd/native-document';
import { projectNativeDocument } from '../../src/formats/exerd/view';
const registry = JSON.parse(readFileSync('app/src/formats/exerd/schema.generated.json', 'utf8')) as BinaryRegistry;

test('new model: worker creation, typed edits, keyboard save, undo, reopen and recovery', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto('/');
  await page.locator('.welcome').getByRole('button', { name: '새 모델', exact: true }).click();
  await page.getByLabel('새 모델 이름').fill('로컬 무계정 검증');
  await page.getByRole('button', { name: '모델 만들기', exact: true }).click();
  await expect(page.locator('.entity-tree > button')).toHaveCount(1);
  await page.locator('.entity-tree > button').first().click();
  await page.getByLabel('테이블 논리명', { exact: true }).fill('저장 직전 é 😀');
  const pendingDownload = page.waitForEvent('download');
  await page.keyboard.press(process.platform === 'darwin' ? 'Meta+s' : 'Control+s');
  const download = await pendingDownload;
  const path = await download.path(); expect(path).toBeTruthy();
  const doc = openNativeDocument(readFileSync(path!), registry as BinaryRegistry);
  expect(projectNativeDocument(doc).allTables[0].logicalName).toBe('저장 직전 é 😀');
  await page.getByRole('button', { name: '실행 취소', exact: true }).click();
  await expect(page.getByLabel('테이블 논리명', { exact: true })).toHaveValue('새 테이블');
  await page.getByRole('button', { name: '다시 실행', exact: true }).click();
  await expect(page.getByLabel('테이블 논리명', { exact: true })).toHaveValue('저장 직전 é 😀');
  await expect(page.locator('.save-state')).toContainText('로컬 복구본 저장됨');
  await page.reload();
  await page.getByRole('button', { name: '이 기기의 이전 작업 복구', exact: true }).click();
  await expect(page.locator('.entity-tree > button')).toHaveCount(1);
  await expect(page.locator('.entity-tree > button').first()).toContainText('저장 직전 é 😀');
  expect(errors).toEqual([]);
  await page.screenshot({ path: 'test-results/new-model.png', fullPage: true });
});

test('user model: 38 diagrams, 609 tables, selected-diagram edits and full native export', async ({ page }) => {
  const file = 'REF/S2B_DA_D00_ERD_20260922_V1.0.exerd';
  test.skip(!existsSync(file), 'Local original is not distributed in Git.');
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto('/');
  await page.getByLabel('eXERD 모델 파일', { exact: true }).setInputFiles(file);
  await expect(page.locator('.entity-tree > button')).toHaveCount(609);
  await expect(page.getByLabel('다이어그램 선택').locator('option')).toHaveCount(39);
  await expect(page.locator('.statusbar')).toContainText('10045 컬럼');
  await page.locator('.entity-tree > button').first().click();
  const label = '브라우저에서 편집 검증';
  await page.getByLabel('테이블 논리명', { exact: true }).fill(label);
  const waiting = page.waitForEvent('download');
  await page.keyboard.press(process.platform === 'darwin' ? 'Meta+s' : 'Control+s');
  const saved = await waiting;
  const path = await saved.path();
  const original = projectNativeDocument(openNativeDocument(readFileSync(file), registry as BinaryRegistry));
  const result = projectNativeDocument(openNativeDocument(readFileSync(path!), registry as BinaryRegistry));
  expect(result.allTables).toHaveLength(609); expect(result.diagrams).toHaveLength(38);
  expect(result.allTables.reduce((n, t) => n + t.columns.length, 0)).toBe(10045);
  expect(result.allRelationships).toHaveLength(561); expect(result.domains).toHaveLength(118); expect(result.placements).toHaveLength(615); expect(result.allNotes).toHaveLength(53);
  expect(result.allTables.filter(t => t.logicalName === label)).toHaveLength(1);
  expect(result.allTables.map(t => t.uuid)).toEqual(original.allTables.map(t => t.uuid));
  mkdirSync('.analysis/compatibility', { recursive: true }); await saved.saveAs('.analysis/compatibility/browser-edited.exerd');
  await page.screenshot({ path: 'test-results/user-model.png', fullPage: true });
  await page.getByLabel('다이어그램 선택').selectOption('');
  await page.getByRole('button', { name: '전체 화면에 맞추기', exact: true }).click();
  await expect(page.locator('.entity-node.compact').first()).toBeVisible();
  await expect(page.locator('.entity-row')).toHaveCount(0);
  await expect(page.locator('.statusbar')).toContainText('10045 컬럼');
  const zoomedDownload = page.waitForEvent('download');
  await page.getByRole('button', { name: '파일 저장', exact: true }).click();
  const zoomed = openNativeDocument(readFileSync((await (await zoomedDownload).path())!), registry);
  const before = openNativeDocument(readFileSync(path!), registry);
  const hash = (data: Uint8Array) => createHash('sha256').update(data).digest('hex');
  expect(hash(zoomed.container.binary)).toBe(hash(before.container.binary));
  expect(hash(zoomed.container.xml)).toBe(hash(before.container.xml));
  await page.screenshot({ path: 'test-results/user-overview.png', fullPage: true });
  expect(errors).toEqual([]);
});
