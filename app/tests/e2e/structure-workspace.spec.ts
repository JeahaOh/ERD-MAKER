import { expect, test } from '@playwright/test';
import { mkdirSync, readFileSync } from 'node:fs';
import type { BinaryRegistry } from '../../src/formats/exerd/binary';
import { openNativeDocument } from '../../src/formats/exerd/native-document';
import { projectNativeDocument } from '../../src/formats/exerd/view';
import { validateNativeDocument } from '../../src/formats/exerd/validation';
const registry = JSON.parse(readFileSync('app/src/formats/exerd/schema.generated.json', 'utf8')) as BinaryRegistry;

test('native structural editing: columns, FK, domain inheritance, diagram copy and undo', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await page.locator('.welcome').getByRole('button', { name: '새 모델', exact: true }).click();
  await page.getByLabel('새 모델 이름').fill('구조 편집 검증');
  await page.getByRole('button', { name: '모델 만들기', exact: true }).click();
  await expect(page.locator('.entity-tree > button')).toHaveCount(1);
  await page.getByRole('button', { name: '테이블 추가', exact: true }).click();
  await expect(page.locator('.entity-tree > button')).toHaveCount(2);
  await page.locator('.entity-tree > button').last().click();
  await page.getByRole('button', { name: '컬럼', exact: true }).click();
  await page.getByLabel('컬럼 추가 이름').fill('parent_id');
  await page.getByRole('button', { name: '적용', exact: true }).click();
  await expect(page.locator('.column-list > button')).toHaveCount(2);
  await page.locator('.entity-tree > button').first().click();
  await page.getByRole('button', { name: '관계', exact: true }).click();
  const relationship = page.getByRole('dialog', { name: '관계 만들기', exact: true });
  await relationship.getByRole('checkbox', { name: /parent_id/ }).check();
  await relationship.getByRole('button', { name: '적용', exact: true }).click();
  await expect(page.locator('.statusbar')).toContainText('1 관계');
  await page.getByRole('button', { name: '도메인 추가', exact: true }).click();
  await page.getByLabel('도메인 추가 이름').fill('부모 식별자');
  await page.getByRole('dialog', { name: '도메인 추가', exact: true }).getByRole('button', { name: '적용', exact: true }).click();
  await expect(page.locator('.statusbar')).toContainText('1 도메인');
  await page.locator('.entity-tree > button').last().click();
  await page.locator('.column-list > button').filter({ hasText: 'parent_id' }).click();
  await page.getByLabel('컬럼 도메인').selectOption({ label: '부모 식별자 · BIGINT' });
  await expect(page.getByLabel('컬럼 도메인')).not.toHaveValue('');
  await page.getByRole('button', { name: '컬럼 위로', exact: true }).click();
  await expect(page.locator('.column-list > button').first()).toContainText('parent_id');
  await page.getByRole('button', { name: '다이어그램', exact: true }).click();
  await page.getByLabel('다이어그램 추가 이름').fill('구조 복제');
  await page.getByRole('checkbox', { name: '현재 다이어그램의 배치·노트 복제', exact: true }).check();
  await page.getByRole('dialog', { name: '다이어그램 추가', exact: true }).getByRole('button', { name: '적용', exact: true }).click();
  await expect(page.getByLabel('다이어그램 선택').locator('option')).toHaveCount(3);
  await page.getByRole('button', { name: '실행 취소', exact: true }).click();
  await expect(page.getByLabel('다이어그램 선택').locator('option')).toHaveCount(2);
  await page.getByRole('button', { name: '다시 실행', exact: true }).click();
  await expect(page.getByLabel('다이어그램 선택').locator('option')).toHaveCount(3);
  await page.getByRole('button', { name: /^검사/ }).click();
  await expect(page.locator('.validation-summary')).toHaveText('오류 0건 · 경고 0건');
  await page.getByRole('button', { name: '확인', exact: true }).click();
  const waiting = page.waitForEvent('download');
  await page.getByRole('button', { name: '파일 저장', exact: true }).click();
  const saved = await waiting;
  const document = openNativeDocument(readFileSync((await saved.path())!), registry);
  const view = projectNativeDocument(document);
  expect(view.allTables).toHaveLength(2); expect(view.allRelationships).toHaveLength(1);
  expect(view.domains).toHaveLength(1); expect(view.diagrams).toHaveLength(2); expect(view.placements).toHaveLength(4);
  expect(view.allTables[1].columns[0].name).toBe('parent_id');
  expect(view.allTables[1].columns[0].domainUuid).toBe(view.domains[0].uuid);
  expect(validateNativeDocument(document)).toEqual([]);
  mkdirSync('.analysis/compatibility', { recursive: true });
  await saved.saveAs('.analysis/compatibility/browser-structure.exerd');
  await page.screenshot({ path: 'test-results/structure-model.png', fullPage: true });
  expect(errors).toEqual([]);
});
